#!/usr/bin/env bash
set -euo pipefail
source "$(dirname "$0")/p163_p5_instrumentation_evidence.sh"
payload="$(cat <<'DATA'
INSTRUMENTATION_RESULT: P5_NATIVE_UI_REAL_ACTIVITY=PASS_INSTRUMENTATION
INSTRUMENTATION_RESULT: P120_ORIGINAL_HOST_ISOLATED_UID=PASS_REAL_ANDROID_BINDER
INSTRUMENTATION_RESULT: P121_ORIGINAL_ENGINE_FD_PREFIX=PASS_REAL_ANDROID_UID_HASH_AND_DENY
INSTRUMENTATION_RESULT: P122_FULL_ENGINE_FD_SHA256=PASS_FULL_57724933_AND_CORRUPTED_REJECTED_NO_EXEC
INSTRUMENTATION_RESULT: P124_FIXED_CHILD_ISOLATED_UID=PASS_SYSTEM_ID_CHILD_MATCHES_FRAMEWORK_ISOLATED_UID_DENY_ALL
INSTRUMENTATION_RESULT: P5_UNTRUSTED_SCHEMA_REJECTION=PASS_ANDROID_FIXTURE
INSTRUMENTATION_CODE: -1
DATA
)"
result="$(p163_check_p5_instrumentation 0 "$payload")"
[[ "$result" == *"P163_P5_ALL_7_ORIGINAL_GATES=PASS"* ]] || exit 1
expect_fail(){
  local status="$1" report="$2" label="$3" result rc
  set +e
  result="$(p163_check_p5_instrumentation "$status" "$report")"
  rc=$?
  set -e
  [[ $rc -ne 0 && "$result" == *"$label"* ]] || {
    echo P163_NEGATIVE_GATE=FAIL;exit 1;
  }
}
expect_fail 1 "$payload" P163_P5_ADB_EXIT_CODE=NONZERO
expect_fail BAD "$payload" P163_P5_ADB_EXIT_CODE=INVALID
expect_fail 0 "${payload/P121_ORIGINAL_ENGINE_FD_PREFIX=PASS_REAL_ANDROID_UID_HASH_AND_DENY/}" P163_P5_MISSING_REQUIRED_MARKER=P121_ORIGINAL_ENGINE_FD_PREFIX
expect_fail 0 "${payload/P122_FULL_ENGINE_FD_SHA256=PASS_FULL_57724933_AND_CORRUPTED_REJECTED_NO_EXEC/}" P163_P5_MISSING_REQUIRED_MARKER=P122_FULL_ENGINE_FD_SHA256
expect_fail 0 "${payload/P124_FIXED_CHILD_ISOLATED_UID=PASS_SYSTEM_ID_CHILD_MATCHES_FRAMEWORK_ISOLATED_UID_DENY_ALL/}" P163_P5_MISSING_REQUIRED_MARKER=P124_FIXED_CHILD_ISOLATED_UID
expect_fail 0 "${payload/INSTRUMENTATION_CODE: -1/INSTRUMENTATION_CODE: 0}" P163_P5_MISSING_REQUIRED_MARKER=INSTRUMENTATION_EXIT
echo P163_FULL_MARKER_POSITIVE_AND_FAIL_CLOSED_NEGATIVES=PASS
echo P163_REAL_ANDROID_EXECUTION_IN_SYNTHETIC_TEST=NO
